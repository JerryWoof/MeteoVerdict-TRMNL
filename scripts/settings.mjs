// Writes src/settings.yml, the plugin's form: the About field (author_bio: the recipe's
// public description, contact and categories), the okres (all 77, from MeteoVerdict's
// index; no default, as TRMNL lowercases select defaults and the codes are upper case),
// the forecast (the combination or the AI: a part of the polling URL), the view, the place name, the evening switch, the wind unit and the language. The okres
// field is `okres_code`, as `okres` is also a key of the forecast file, and the forecast
// field `forecast_model`, as `forecast` is one too.
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const index = await (await fetch("https://meteoverdict.cz/api/v1/index.json")).json();
const label = (o) => (o.code === "CZ0100" ? "Praha" : o.name);
const okresy = index.okresy.map((o) => [label(o), o.code]).sort((a, b) => a[0].localeCompare(b[0], "cs"));
const q = (s) => JSON.stringify(s);
const yml = `# The plugin's form (TRMNL custom fields). Generated by scripts/settings.mjs.
- keyname: about
  field_type: author_bio
  name: About This Plugin
  description: >-
    Weather for your Czech district (okres) on your TRMNL: today and tomorrow, the next
    24 or 48 hours or five days, with temperature and its range, rain with its
    timing and chance, sunshine, clouds, wind, sunrise and sunset, and badges for frost,
    rain, gusts and heat.<br/><br/>
    The forecast is <a href="https://meteoverdict.cz/" class="underline">MeteoVerdict</a>'s.
    Every day it checks how well about 20 weather models forecast what ČHMÚ stations then
    measured, and blends them, weighting each model by how accurate it has been in your
    okres over the last 90 days. By default the forecast is MeteoVerdict
    AI's, its own AI model. Free, no API key, no account.<br/><br/>
    Počasí pro váš okres podle MeteoVerdictu, česky i anglicky.<br/><br/>
    The badges are MeteoVerdict's thresholds, not official ČHMÚ warnings
    (<a href="https://www.chmi.cz/" class="underline">chmi.cz</a>). Questions and bugs:
    <a href="https://github.com/JerryWoof/MeteoVerdict-TRMNL/issues" class="underline">GitHub issues</a>. Forecast data ©
    MeteoVerdict, CC BY-SA 4.0, built from Open-Meteo.com, ČHMÚ and the weather services'
    model data. Not affiliated with TRMNL, ČHMÚ or Open-Meteo.
  github_url: https://github.com/JerryWoof/MeteoVerdict-TRMNL
  learn_more_url: https://meteoverdict.cz/
  category: environment,life
- keyname: okres_code
  field_type: select
  name: Okres
  description: Your district. The forecast is MeteoVerdict's combined forecast for it.
  options:
${okresy.map(([name, code]) => `  - ${q(name)}: ${code}`).join("\n")}
- keyname: forecast_model
  field_type: select
  name: Forecast
  description: MeteoVerdict AI (MeteoVerdict's own AI model), or MeteoVerdict's combined forecast of all models, with the range of the temperature.
  options:
  - "MeteoVerdict AI": ai/okresy
  - "MeteoVerdict (all models combined)": okresy
  default: ai/okresy
- keyname: view
  field_type: select
  name: View (full screen)
  description: What the screen shows.
  options:
  - "Today and tomorrow": today_tomorrow
  - "Next 24 hours": next_24h
  - "Next 48 hours": next_48h
  - "5 days": five_days
  default: today_tomorrow
- keyname: place
  field_type: string
  name: Place name
  description: Shown in the title bar instead of the okres name, e.g. your town.
  placeholder: Říčany
  optional: true
- keyname: evening_switch
  field_type: boolean
  name: Move on to tomorrow in the evening
  description: After 18:00 the day layouts show tomorrow and the day after instead of today and tomorrow.
  default: true
- keyname: wind_unit
  field_type: select
  name: Wind speed in
  options:
  - "m/s": ms
  - "km/h": kmh
  default: ms
- keyname: language
  field_type: select
  name: Language
  options:
  - "English": en
  - "Čeština": cs
  default: en
`;
writeFileSync(join(root, "src", "settings.yml"), yml);
console.log(`src/settings.yml: ${okresy.length} okresy`);
