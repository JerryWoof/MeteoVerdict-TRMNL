// Writes src/settings.yml, the plugin's form: the About field (author_bio: the recipe's
// public description, contact and categories), the okres (all 77, from MeteoVerdict's
// index; no default, as TRMNL lowercases select defaults and the codes are upper case),
// the view, the place name, the evening switch, the wind unit and the language. The okres
// field is `okres_code`, as `okres` is also a key of the forecast file.
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const index = await (await fetch("https://jerrywoof.github.io/MeteoVerdict/api/v1/index.json")).json();
const label = (o) => (o.code === "CZ0100" ? "Praha" : o.name);
const okresy = index.okresy.map((o) => [label(o), o.code]).sort((a, b) => a[0].localeCompare(b[0], "cs"));
const q = (s) => JSON.stringify(s);
const yml = `# The plugin's form (TRMNL custom fields). Generated by scripts/settings.mjs.
- keyname: about
  field_type: author_bio
  name: About This Plugin
  description: >-
    Weather for your Czech district (okres) on your TRMNL: today and tomorrow, the next
    24 hours, five days or the weekend, with temperature, rain and its chance, sunshine,
    clouds, wind, sunrise and sunset, and badges for frost, black ice, heavy rain, strong
    wind and heat. Compact layouts for half and quarter screens let you show two or four
    places at once, or the weather next to your calendar.<br/><br/>
    The forecast is <a href="https://jerrywoof.github.io/MeteoVerdict/" class="underline">MeteoVerdict</a>'s.
    Every day it checks how well 11 weather models forecast what ČHMÚ stations then
    measured, and blends them, weighting each model by how accurate it has been in your
    okres over the last 90 days. Free, no API key, no account.<br/><br/>
    Počasí pro váš okres podle MeteoVerdictu, česky i anglicky.<br/><br/>
    Pick your okres (all 77), the view and the language below. Questions and bugs:
    <a href="https://github.com/JerryWoof/MeteoVerdict-TRMNL/issues" class="underline">GitHub issues</a>. Forecast data ©
    MeteoVerdict, CC BY-SA 4.0, built from Open-Meteo.com and ČHMÚ data. Not affiliated
    with TRMNL, ČHMÚ or Open-Meteo.
  github_url: https://github.com/JerryWoof/MeteoVerdict-TRMNL
  learn_more_url: https://jerrywoof.github.io/MeteoVerdict/
  category: environment,life
- keyname: okres_code
  field_type: select
  name: Okres
  description: Your district. The forecast is MeteoVerdict's combined forecast for it.
  options:
${okresy.map(([name, code]) => `  - ${q(name)}: ${code}`).join("\n")}
- keyname: view
  field_type: select
  name: View (full screen)
  description: What the full screen shows. Half and quarter screens always show today and the next days.
  options:
  - "Today and tomorrow": today_tomorrow
  - "Next 24 hours": next_24h
  - "5 days": five_days
  - "Weekend": weekend
  default: today_tomorrow
- keyname: place
  field_type: string
  name: Place name
  description: Shown in the title bar instead of the okres name, e.g. your town.
  placeholder: Říčany
  optional: true
- keyname: evening_switch
  field_type: boolean
  name: Move on to tomorrow in the evening
  description: After 18:00 the day layouts show tomorrow and the day after instead of today and tomorrow, and the weekend view looks a day ahead (on Sunday evening, the next weekend).
  default: true
- keyname: wind_unit
  field_type: select
  name: Wind speed in
  options:
  - "m/s": ms
  - "km/h": kmh
  default: ms
- keyname: language
  field_type: select
  name: Language
  options:
  - "English": en
  - "Čeština": cs
  default: en
`;
writeFileSync(join(root, "src", "settings.yml"), yml);
console.log(`src/settings.yml: ${okresy.length} okresy`);
