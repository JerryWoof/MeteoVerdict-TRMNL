// Writes src/settings.yml, the plugin's form: the okres (all 77, from MeteoVerdict's
// index), the view, the place name and the language.
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const index = await (await fetch("https://jerrywoof.github.io/MeteoVerdict/api/v1/index.json")).json();
const label = (o) => (o.code === "CZ0100" ? "Praha" : o.name);
const okresy = index.okresy.map((o) => [label(o), o.code]).sort((a, b) => a[0].localeCompare(b[0], "cs"));
const q = (s) => JSON.stringify(s);
const yml = `# The plugin's form (TRMNL custom fields). Generated by scripts/settings.mjs.
- keyname: okres
  field_type: select
  name: Okres
  description: Your district. The forecast is MeteoVerdict's combined forecast for it.
  options:
${okresy.map(([name, code]) => `  - ${q(name)}: ${code}`).join("\n")}
  default: CZ0100
- keyname: view
  field_type: select
  name: View (full screen)
  description: What the full screen shows. Half and quarter screens always show today and the next days.
  options:
  - "Today and tomorrow": today_tomorrow
  - "Next 24 hours": next_24h
  - "5 days": five_days
  default: today_tomorrow
- keyname: place
  field_type: string
  name: Place name
  description: Shown in the title bar instead of the okres name, e.g. your town.
  optional: true
- keyname: language
  field_type: select
  name: Language
  options:
  - "English": en
  - "Čeština": cs
  default: en
`;
writeFileSync(join(root, "src", "settings.yml"), yml);
console.log(`src/settings.yml: ${okresy.length} okresy`);
